"""Assemble the openharmony/ets SDK directory from the 4 OH SDK dynamic ets
components (api, arkts, component, kits) produced at ohos_dynamic/.

The 4 component directories are merged into a single ets/ directory, matching
the OH OS SDK ets package layout expected under arkui-x/openharmony/ets.

The ets-loader config files (build_config.json, component_config.json,
form_config.json) generated by developtools/ace_ets2bundle:build_ets_loader_library
are copied into ets/component/ alongside the component .d.ets declarations,
matching the OH OS SDK ets/dynamic/component/ layout.

An oh-uni-package.json metadata file is generated alongside the assembled
components so that the ArkUI-X build (./build.sh) produces a complete ets
package without depending on the external prebuilt_sdk.py merge flow.
"""

import argparse
import json
import os
import shutil
import sys


def copy_component(src, dest_root, dest_name):
    """Copy a component directory into dest_root as dest_name.

    Exits with an error if the source directory is missing, since all four
    components (api, arkts, component, kits) are required for a complete ets
    package.
    """
    if not os.path.isdir(src):
        print('Error: required ets component directory not found: {}'.format(src),
              file=sys.stderr)
        sys.exit(1)
    dest = os.path.join(dest_root, dest_name)
    shutil.copytree(src, dest, dirs_exist_ok=True)


def copy_config_file(src, dest_dir):
    """Copy a single ets-loader config file (e.g. build_config.json) into dest_dir.

    Exits with an error if the source file is missing, since the ets-loader
    config files are required for a complete ets package.
    """
    if not os.path.isfile(src):
        print('Error: required ets-loader config file not found: {}'.format(src),
              file=sys.stderr)
        sys.exit(1)
    shutil.copy2(src, os.path.join(dest_dir, os.path.basename(src)))


def write_oh_uni_package(output_dir, api_version, platform_version,
                         sdk_version, release_type, meta_version):
    """Write oh-uni-package.json metadata into the assembled ets directory.

    The format mirrors the OH OS SDK ets package metadata generated by
    build/ohos/sdk/generate_all_types_sdk.py, so IDEs and tooling that consume
    the openharmony/ets package can read version info consistently.
    """
    package_info = {
        "path": "ets",
        "displayName": "ets",
        "version": sdk_version,
        "apiVersion": api_version,
        "platformVersion": platform_version,
    }
    if release_type:
        package_info["releaseType"] = release_type
    if meta_version:
        package_info["meta"] = {"metaVersion": meta_version}

    output_file = os.path.join(output_dir, "oh-uni-package.json")
    with open(output_file, "w", encoding="utf-8") as f:
        json.dump(package_info, f, indent=2, sort_keys=True)
        f.write("\n")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--api', required=True)
    parser.add_argument('--arkts', required=True)
    parser.add_argument('--component', required=True)
    parser.add_argument('--kits', required=True)
    parser.add_argument('--output', required=True)
    parser.add_argument('--api-version', default='')
    parser.add_argument('--platform-version', default='')
    parser.add_argument('--sdk-version', default='')
    parser.add_argument('--release-type', default='')
    parser.add_argument('--meta-version', default='')
    parser.add_argument('--build-config', required=True)
    parser.add_argument('--component-config', required=True)
    parser.add_argument('--form-config', required=True)
    args = parser.parse_args()

    # Clean the output directory to avoid stale files (e.g. deleted .d.ts)
    # persisting across incremental builds.
    shutil.rmtree(args.output, ignore_errors=True)
    os.makedirs(args.output, exist_ok=True)
    copy_component(args.api, args.output, "api")
    copy_component(args.arkts, args.output, "arkts")
    copy_component(args.component, args.output, "component")
    copy_component(args.kits, args.output, "kits")

    # Copy the ets-loader config files into ets/component/, matching the OH OS
    # SDK ets/dynamic/component/ layout where build_config.json,
    # component_config.json and form_config.json sit alongside the component
    # .d.ets declarations. Generated by build_ets_loader_library.
    component_dir = os.path.join(args.output, "component")
    copy_config_file(args.build_config, component_dir)
    copy_config_file(args.component_config, component_dir)
    copy_config_file(args.form_config, component_dir)

    # Generate oh-uni-package.json so the assembled ets package carries version
    # metadata without relying on the prebuilt_sdk.py merge step.
    if args.sdk_version:
        write_oh_uni_package(
            args.output, args.api_version, args.platform_version,
            args.sdk_version, args.release_type, args.meta_version)


if __name__ == '__main__':
    sys.exit(main())
