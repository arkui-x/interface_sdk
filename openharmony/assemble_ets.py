"""Assemble the openharmony/ets SDK directory from the 4 OH SDK dynamic ets
components (api, arkts, component, kits) produced at ohos_dynamic/.

The 4 component directories are merged into a single ets/ directory, matching
the OH OS SDK ets package layout expected under arkui-x/openharmony/ets.

The ets-loader config files (build_config.json, component_config.json,
form_config.json) generated by developtools/ace_ets2bundle:build_ets_loader_library
are copied into ets/component/ alongside the component .d.ets declarations,
matching the OH OS SDK ets/dynamic/component/ layout.

@systemapi declarations are stripped from ets/api by running
delete_systemapi_plugin.js (the same tool the OH public SDK uses when built with
sdk_build_public), so the ArkUI-X SDK excludes system APIs by default. The tool
runs after assembly so the full api/arkts/kits layout is available for
cross-reference resolution.

An oh-uni-package.json metadata file is generated alongside the assembled
components so that the ArkUI-X build (./build.sh) produces a complete ets
package without depending on the external prebuilt_sdk.py merge flow.
"""

import argparse
import json
import os
import re
import shutil
import subprocess
import sys


def copy_component(src, dest_root, dest_name):
    """Copy a component directory into dest_root as dest_name.

    Exits with an error if the source directory is missing, since all four
    components (api, arkts, component, kits) are required for a complete ets
    package.
    """
    if not os.path.isdir(src):
        print('Error: required ets component directory not found: {}'.format(src),
              file=sys.stderr)
        sys.exit(1)
    dest = os.path.join(dest_root, dest_name)
    shutil.copytree(src, dest, dirs_exist_ok=True)


def copy_config_file(src, dest_dir):
    """Copy a single ets-loader config file (e.g. build_config.json) into dest_dir.

    Exits with an error if the source file is missing, since the ets-loader
    config files are required for a complete ets package.
    """
    if not os.path.isfile(src):
        print('Error: required ets-loader config file not found: {}'.format(src),
              file=sys.stderr)
        sys.exit(1)
    shutil.copy2(src, os.path.join(dest_dir, os.path.basename(src)))


def _replace_with_generated(gen_dir, target_dir, label, log):
    """Replace target_dir with the tool's generated output.

    Hard-fails if gen_dir is missing, so a partial tool failure (e.g. api
    produced but kits/arkts missing) does not silently leave unstripped
    directories pointing at symbols already removed from api.
    """
    if not os.path.isdir(gen_dir):
        print('Error: delete_systemapi_plugin produced no {} output; '
              '{} stripping did not complete.\n{}'.format(label, label, log),
              file=sys.stderr)
        sys.exit(1)
    shutil.rmtree(target_dir, ignore_errors=True)
    shutil.move(gen_dir, target_dir)


def delete_systemapi(output_dir, node_js, tool_path, build_sdk_path, sdk_type):
    """Strip @systemapi declarations from the assembled ets package.

    Mirrors remove_system_api_method + replace_sdk_dir in
    build/ohos/sdk/parse_interface_sdk.py: delete_systemapi_plugin.js reads
    <output>/api (referencing sibling arkts/kits for cross-resolution), writes
    stripped results to <output>/build-tools/{api,kits,arkts}, then each
    generated dir replaces the corresponding original so kits and arkts stay
    consistent with the stripped api. The ArkUI-X dynamic SDK path does not
    consult sdk_build_public, so this runs by default to keep system APIs out
    of the released SDK.

    The tool expects component declarations under <input>/@internal/component/
    ets/ (the OH SDK layout where component files live under api/). The ArkUI-X
    assembly separates them into ets/component/, so component is temporarily
    moved under ets/api/@internal/component/ets/ before the tool runs and moved
    back afterwards. This lets the tool strip @systemapi from component
    declarations too (e.g. grid.d.ts), matching the OH public SDK where
    delete_systemapi_plugin.js processes api/@internal/component/ets/ as part
    of api/ (readFile recurses).
    """
    api_dir = os.path.join(output_dir, "api")
    kits_dir = os.path.join(output_dir, "kits")
    arkts_dir = os.path.join(output_dir, "arkts")
    component_dir = os.path.join(output_dir, "component")
    modify_dir = os.path.join(output_dir, "build-tools")

    # Temporarily move ets/component/ under ets/api/@internal/component/ets/
    # so the tool processes component @systemapi. The tool's
    # collectComponentEtsFiles() reads inputDir/@internal/component/ets, which
    # only exists if component is placed there (remove_internal.py strips
    # @internal from the dynamic api, so ets/api/ does not have it).
    temp_component_dir = os.path.join(api_dir, "@internal", "component", "ets")
    moved_component = False
    if os.path.isdir(component_dir):
        os.makedirs(os.path.dirname(temp_component_dir), exist_ok=True)
        shutil.move(component_dir, temp_component_dir)
        moved_component = True

    # Use absolute paths: entry.js loads koala-wrapper's es2panda via
    # require(sdkPath + '/build-tools/...'); Node only treats paths starting
    # with /, ./, ../ as file paths, so a relative build_sdk_path would be
    # misread as a package name. Matches os.path.abspath in
    # build/ohos/sdk/parse_interface_sdk.py.
    cmd = [node_js, tool_path,
           "--input", os.path.abspath(api_dir),
           "--output", os.path.abspath(modify_dir),
           "--type", sdk_type,
           "--build-sdk-path", os.path.abspath(build_sdk_path)]
    proc = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    if proc.returncode != 0:
        print('Error: delete_systemapi_plugin failed:\n{}'.format(
            proc.stdout.decode('utf-8', 'replace')), file=sys.stderr)
        sys.exit(1)
    gen_api_dir = os.path.join(modify_dir, "api")
    gen_kits_dir = os.path.join(modify_dir, "kits")
    gen_arkts_dir = os.path.join(modify_dir, "arkts")
    log = proc.stdout.decode('utf-8', 'replace')
    # delete_systemapi_plugin.js wraps its work in try/catch and exits 0 even on
    # failure, so returncode alone cannot detect it. Hard-fail on any missing
    # output directory so the build does not silently ship an unstripped or
    # inconsistent SDK.
    if not os.path.isdir(gen_api_dir):
        print('Error: delete_systemapi_plugin produced no api output; '
              '@systemapi stripping did not complete.\n{}'.format(log),
              file=sys.stderr)
        sys.exit(1)
    # When component was moved under api/@internal/component/ets/, verify the
    # tool's output also contains the stripped component. Without this check, a
    # partial tool failure (exit 0 + gen_api_dir exists but missing component)
    # would cause rmtree(api_dir) below to destroy the original component
    # declarations, leaving the SDK silently missing all component files.
    if moved_component:
        gen_component_dir = os.path.join(
            gen_api_dir, "@internal", "component", "ets")
        if not os.path.isdir(gen_component_dir):
            print('Error: delete_systemapi_plugin produced no component output; '
                  'component stripping did not complete.\n{}'.format(log),
                  file=sys.stderr)
            sys.exit(1)
    # Replace api, kits, and arkts with the tool's stripped output. Kits and
    # arkts must stay consistent with the stripped api (kits may reference
    # symbols removed from api; arkts is processed alongside api by the same
    # tsTransform pass).
    _replace_with_generated(gen_api_dir, api_dir, "api", log)
    _replace_with_generated(gen_kits_dir, kits_dir, "kits", log)
    _replace_with_generated(gen_arkts_dir, arkts_dir, "arkts", log)

    # Move the stripped component declarations back to ets/component/.
    if moved_component:
        stripped_component = os.path.join(
            api_dir, "@internal", "component", "ets")
        if os.path.isdir(stripped_component):
            shutil.rmtree(component_dir, ignore_errors=True)
            shutil.move(stripped_component, component_dir)
        # Clean up the now-empty @internal/component and @internal dirs that
        # were only created to host component during the tool run.
        _internal_component = os.path.join(api_dir, "@internal", "component")
        if os.path.isdir(_internal_component) and not os.listdir(_internal_component):
            os.rmdir(_internal_component)
        _internal_root = os.path.join(api_dir, "@internal")
        if os.path.isdir(_internal_root) and not os.listdir(_internal_root):
            os.rmdir(_internal_root)

    shutil.rmtree(modify_dir, ignore_errors=True)


def package_declarations(output_dir, node_js, transform_tool):
    """Package global.d.ts, featureability.d.ts, bundleStatusCallback.d.ts into ets/component/.

    These files are generated by build_declarations_file.js for the OH SDK's
    ets-loader/declarations. Since ArkUI-X SDK does not include ets-loader,
    they are packaged into ets/component/ instead.

    - global.d.ts: from api/@internal/full/, processsFile transform + license header
    - featureability.d.ts: from api/@internal/full/, processsFile transform
    - bundleStatusCallback.d.ts: from api/bundle/, import path rewrite (../api/ -> ../../)
    """
    component_dir = os.path.join(output_dir, "component")
    api_dir = os.path.join(output_dir, "api")

    # bundleStatusCallback.d.ts: copy from api/bundle/ with import path rewrite.
    # build_declarations_file.js rewrites import("../api/...") to import("../../...")
    # so paths resolve from ets/component/ instead of ets/api/bundle/.
    bundle_src = os.path.join(api_dir, "bundle", "bundleStatusCallback.d.ts")
    if os.path.isfile(bundle_src):
        with open(bundle_src, "r", encoding="utf-8") as f:
            content = f.read()
        content = re.sub(r'(import\s*\(("|\'))(\.\.\/api\/)', r'\1../../', content)
        with open(os.path.join(component_dir, "bundleStatusCallback.d.ts"),
                  "w", encoding="utf-8") as f:
            f.write(content)
    else:
        print('Warning: bundleStatusCallback.d.ts source not found at {}, '
              'skipping'.format(bundle_src), file=sys.stderr)

    # global.d.ts and featureability.d.ts: transform via Node.js script.
    # processsFile removes import declarations, strips export modifiers, and
    # swaps variable name<->type (same as build_declarations_file.js for OH SDK).
    for filename, add_license in [("global.d.ts", True),
                                  ("featureability.d.ts", False)]:
        src = os.path.join(api_dir, "@internal", "full", filename)
        if not os.path.isfile(src):
            print('Warning: {} source not found at {}, skipping'.format(
                filename, src), file=sys.stderr)
            continue
        dst = os.path.join(component_dir, filename)
        cmd = [node_js, transform_tool,
               "--input", os.path.abspath(src),
               "--output", os.path.abspath(dst)]
        if add_license:
            cmd.append("--add-license")
        proc = subprocess.run(cmd, stdout=subprocess.PIPE,
                              stderr=subprocess.STDOUT)
        if proc.returncode != 0:
            print('Error: transform_declarations failed for {}: \n{}'.format(
                filename, proc.stdout.decode('utf-8', 'replace')),
                file=sys.stderr)
            sys.exit(1)


def write_oh_uni_package(output_dir, api_version, platform_version,
                         sdk_version, release_type, meta_version):
    """Write oh-uni-package.json metadata into the assembled ets directory.

    The format mirrors the OH OS SDK ets package metadata generated by
    build/ohos/sdk/generate_all_types_sdk.py, so IDEs and tooling that consume
    the openharmony/ets package can read version info consistently.
    """
    package_info = {
        "path": "ets",
        "displayName": "ets",
        "version": sdk_version,
        "apiVersion": api_version,
        "platformVersion": platform_version,
    }
    if release_type:
        package_info["releaseType"] = release_type
    if meta_version:
        package_info["meta"] = {"metaVersion": meta_version}

    output_file = os.path.join(output_dir, "oh-uni-package.json")
    with open(output_file, "w", encoding="utf-8") as f:
        json.dump(package_info, f, indent=2, sort_keys=True)
        f.write("\n")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--api', required=True)
    parser.add_argument('--arkts', required=True)
    parser.add_argument('--component', required=True)
    parser.add_argument('--kits', required=True)
    parser.add_argument('--output', required=True)
    parser.add_argument('--api-version', default='')
    parser.add_argument('--platform-version', default='')
    parser.add_argument('--sdk-version', default='')
    parser.add_argument('--release-type', default='')
    parser.add_argument('--meta-version', default='')
    parser.add_argument('--build-config', required=True)
    parser.add_argument('--component-config', required=True)
    parser.add_argument('--form-config', required=True)
    parser.add_argument('--node-js', required=True)
    parser.add_argument('--systemapi-tool', required=True)
    parser.add_argument('--build-sdk-path', required=True)
    parser.add_argument('--sdk-type', required=True)
    parser.add_argument('--include-systemapi', default='false')
    parser.add_argument('--declarations-transform-tool', required=True)
    args = parser.parse_args()

    # Clean the output directory to avoid stale files (e.g. deleted .d.ts)
    # persisting across incremental builds.
    shutil.rmtree(args.output, ignore_errors=True)
    os.makedirs(args.output, exist_ok=True)
    copy_component(args.api, args.output, "api")
    copy_component(args.arkts, args.output, "arkts")
    copy_component(args.component, args.output, "component")
    copy_component(args.kits, args.output, "kits")

    # Copy the ets-loader config files into ets/component/, matching the OH OS
    # SDK ets/dynamic/component/ layout where build_config.json,
    # component_config.json and form_config.json sit alongside the component
    # .d.ets declarations. Generated by build_ets_loader_library.
    component_dir = os.path.join(args.output, "component")
    copy_config_file(args.build_config, component_dir)
    copy_config_file(args.component_config, component_dir)
    copy_config_file(args.form_config, component_dir)

    # Strip @systemapi declarations from ets/api so the ArkUI-X SDK excludes
    # system APIs by default. Runs after assembly so delete_systemapi_plugin.js
    # can resolve cross-references against the sibling arkts/kits dirs.
    # Skipped when include_oh_system_api=true (keep @systemapi in the SDK).
    if args.include_systemapi != 'true':
        delete_systemapi(args.output, args.node_js, args.systemapi_tool,
                         args.build_sdk_path, args.sdk_type)

    # Package global.d.ts, featureability.d.ts, bundleStatusCallback.d.ts into
    # ets/component/. These are normally in ets-loader/declarations (built by
    # build_declarations_file.js) but ArkUI-X SDK does not include ets-loader.
    package_declarations(args.output, args.node_js, args.declarations_transform_tool)

    # Generate oh-uni-package.json so the assembled ets package carries version
    # metadata without relying on the prebuilt_sdk.py merge step.
    if args.sdk_version:
        write_oh_uni_package(
            args.output, args.api_version, args.platform_version,
            args.sdk_version, args.release_type, args.meta_version)


if __name__ == '__main__':
    sys.exit(main())
